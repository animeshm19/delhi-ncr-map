// Builds supabase/seed.sql from data/areas.json and data/seed.json, so the SQL used by the
// database tests, the end-to-end stack and a fresh Supabase project always matches the JSON.
//
//   node scripts/build-seed-sql.mjs            # writes supabase/seed.sql
//   node scripts/build-seed-sql.mjs --check    # exits 1 if supabase/seed.sql is out of date
//
// Safe to run more than once against a database: areas and organisations are upserts,
// sources and relationships skip rows that are already there.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const areas = JSON.parse(fs.readFileSync(path.join(ROOT, "data/areas.json"), "utf8"));
const orgs = JSON.parse(fs.readFileSync(path.join(ROOT, "data/seed.json"), "utf8"));

const q = (v) => (v == null ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (xs) => `array[${xs.map(q).join(",")}]::text[]`;
const num = (v) => (v == null ? "null" : String(Number(v)));
const point = ([lng, lat]) =>
  `extensions.st_setsrid(extensions.st_makepoint(${Number(lng)},${Number(lat)}),4326)::extensions.geography`;

const out = [];
out.push(
  "-- Generated by scripts/build-seed-sql.mjs from data/*.json. Do not edit by hand.",
  "insert into areas (slug,name,center,radius_m) values",
  areas.map((a) => `(${q(a.slug)},${q(a.name)},${point(a.center)},${num(a.radius_m)})`).join(",\n"),
  "on conflict (slug) do update set name=excluded.name, center=excluded.center, radius_m=excluded.radius_m;",
  "",
);

const cols = "slug,name,kind,sectors,status,one_liner,website,founded_year,municipality,area,location_precision,funding_note,hiring,verification,published,updated_at";
out.push(
  `insert into organizations (${cols}) values`,
  orgs
    .map(
      (o) =>
        `(${q(o.slug)},${q(o.name)},${q(o.kind)}::org_kind,${arr(o.sectors)},${q(o.status)}::org_status,${q(o.one_liner)},` +
        `${q(o.website)},${num(o.founded_year)},${q(o.municipality)},${q(o.area)},${q(o.location_precision)}::loc_precision,` +
        `${q(o.funding_note)},${o.hiring == null ? "null" : o.hiring},${q(o.verification)}::verification,true,${q(o.updated_at)}::timestamptz)`,
    )
    .join(",\n"),
  "on conflict (slug) do update set " +
    cols
      .split(",")
      .filter((c) => c !== "slug")
      .map((c) => `${c}=excluded.${c}`)
      .join(",") +
    ";",
  "",
);

for (const o of orgs.filter((o) => o.acquired_by)) {
  out.push(`update organizations set acquired_by=${q(o.acquired_by)} where slug=${q(o.slug)};`);
}
out.push("");

const sources = orgs.flatMap((o) => o.sources.map((s) => ({ ...s, org: o.slug })));
out.push(
  "insert into sources (org_slug,url,note,fields,retrieved)",
  "select v.org_slug, v.url, v.note, v.fields, v.retrieved from (values",
  sources.map((s) => `(${q(s.org)},${q(s.url)},${q(s.note)},${arr(s.fields)},${q(s.retrieved)}::date)`).join(",\n"),
  ") as v(org_slug,url,note,fields,retrieved)",
  "where not exists (select 1 from sources s where s.org_slug = v.org_slug and s.url = v.url and s.fields = v.fields);",
  "",
);

const rels = orgs.flatMap((o) => (o.relationships ?? []).map((r) => ({ ...r, from: o.slug })));
const existingRels = fs.readFileSync(path.join(ROOT, "data/relationships.json"), "utf8");
const relRows = JSON.parse(existingRels).concat(rels);
if (relRows.length) {
  out.push(
    "insert into relationships (from_slug,to_slug,relation,source_url) values",
    relRows.map((r) => `(${q(r.from)},${q(r.to)},${q(r.relation)},${q(r.source_url)})`).join(",\n"),
    "on conflict (from_slug,to_slug,relation) do nothing;",
    "",
  );
}

const sql = out.join("\n");
const file = path.join(ROOT, "supabase/seed.sql");
if (process.argv.includes("--check")) {
  if (fs.readFileSync(file, "utf8") !== sql) {
    console.error("supabase/seed.sql is out of date: run node scripts/build-seed-sql.mjs");
    process.exit(1);
  }
  console.log("supabase/seed.sql is up to date");
} else {
  fs.writeFileSync(file, sql);
  console.log(`wrote ${areas.length} areas, ${orgs.length} organisations, ${sources.length} sources, ${relRows.length} relationships`);
}
